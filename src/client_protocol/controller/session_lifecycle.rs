    pub fn revert_to_user_anchor(&mut self, session_id: &str, seq: u64) -> anyhow::Result<()> {
        let project = self.project.clone();
        let binding = self.session_binding(session_id);
        if self.projection(session_id).is_none() {
            return Err(anyhow::anyhow!("no session bound"));
        }
        let outcome = self.service.revert_to_user_anchor(session_id, seq);
        let Some(proj) = self.projection_mut(session_id) else {
            unreachable!("projection checked above");
        };
        match outcome {
            Ok(guard) => {
                proj.apply_reverted(&project, &binding);
                // Keep the exclusive revert lease through the projection
                // refresh and its emitted frames; release only afterwards.
                drop(guard);
                Ok(())
            }
            Err(crate::session::service::RevertError::Busy) => {
                proj.push_operation_error(
                    OperationKind::RevertToUserAnchor,
                    ErrorCode::AgentAlreadyRunning,
                    "session is busy".into(),
                    &project,
                    &binding,
                );
                Ok(())
            }
            Err(crate::session::service::RevertError::InvalidAnchor(msg)) => {
                proj.push_operation_error(
                    OperationKind::RevertToUserAnchor,
                    ErrorCode::InvalidRevertAnchor,
                    msg,
                    &project,
                    &binding,
                );
                Ok(())
            }
            Err(crate::session::service::RevertError::Internal(msg)) => {
                proj.push_operation_error(
                    OperationKind::RevertToUserAnchor,
                    ErrorCode::Internal,
                    msg,
                    &project,
                    &binding,
                );
                Ok(())
            }
            Err(crate::session::service::RevertError::Fatal(error)) => Err(error.into()),
        }
    }

    pub fn revert_files(&mut self, session_id: &str, seq: u64) -> anyhow::Result<()> {
        let project = self.project.clone();
        let binding = self.session_binding(session_id);
        let workspace_root = self.project.clone();
        let snapshots_dir = self.runtime.workspace.paths.snapshots_dir.clone();
        if self.projection(session_id).is_none() {
            return Err(anyhow::anyhow!("no session bound"));
        }
        let plan_result = self.service.begin_file_revert(session_id, seq);
        let Some(proj) = self.projection_mut(session_id) else {
            unreachable!("projection checked above");
        };
        let plan = match plan_result {
            Ok(plan) => plan,
            Err(crate::session::service::RevertError::Busy) => {
                proj.push_operation_error(
                    OperationKind::RevertFiles,
                    ErrorCode::AgentAlreadyRunning,
                    "session is busy".into(),
                    &project,
                    &binding,
                );
                return Ok(());
            }
            Err(crate::session::service::RevertError::InvalidAnchor(msg)) => {
                proj.push_operation_error(
                    OperationKind::RevertFiles,
                    ErrorCode::InvalidRevertAnchor,
                    msg,
                    &project,
                    &binding,
                );
                return Ok(());
            }
            Err(crate::session::service::RevertError::Internal(msg)) => {
                proj.push_operation_error(
                    OperationKind::RevertFiles,
                    ErrorCode::Internal,
                    msg,
                    &project,
                    &binding,
                );
                return Ok(());
            }
            Err(crate::session::service::RevertError::Fatal(error)) => {
                return Err(error.into());
            }
        };
        let stem = plan.stem();
        let workspace = std::path::PathBuf::from(workspace_root);
        let snaps = snapshots_dir.to_path_buf();
        let sid = session_id.to_string();
        let restore_result = super::run_snapshot_restore_off_async(workspace, snaps, sid, stem);
        // Keep the exclusive file-revert lease through the workspace restore
        // and the projection frames that publish its result.
        let result = match restore_result {
            Ok(crate::session::snapshot::RestoreOutcome::Restored { .. }) => {
                proj.push_operation_ok(OperationKind::RevertFiles, &project, &binding);
                Ok(())
            }
            Ok(crate::session::snapshot::RestoreOutcome::NothingToRevert) => {
                proj.push_operation_error(
                    OperationKind::RevertFiles,
                    ErrorCode::NothingToRevert,
                    "no file changes to revert".into(),
                    &project,
                    &binding,
                );
                Ok(())
            }
            Ok(crate::session::snapshot::RestoreOutcome::Unavailable {
                reason: crate::session::snapshot::RestoreUnavailable::MissingTrackRef,
            }) => {
                proj.push_operation_error(
                    OperationKind::RevertFiles,
                    ErrorCode::SnapshotUnavailable,
                    "no file snapshot for this anchor (track may have failed)".into(),
                    &project,
                    &binding,
                );
                Ok(())
            }
            Ok(crate::session::snapshot::RestoreOutcome::Unavailable {
                reason: crate::session::snapshot::RestoreUnavailable::TrackFailed,
            }) => {
                proj.push_operation_error(
                    OperationKind::RevertFiles,
                    ErrorCode::SnapshotUnavailable,
                    "file snapshot unavailable (track failed this turn)".into(),
                    &project,
                    &binding,
                );
                Ok(())
            }
            Err(LitecodeError::InvalidRevertAnchor(msg)) => {
                proj.push_operation_error(
                    OperationKind::RevertFiles,
                    ErrorCode::InvalidRevertAnchor,
                    msg,
                    &project,
                    &binding,
                );
                Ok(())
            }
            Err(error) => {
                proj.push_operation_error(
                    OperationKind::RevertFiles,
                    ErrorCode::Internal,
                    error.to_string(),
                    &project,
                    &binding,
                );
                Ok(())
            }
        };
        drop(plan);
        result
    }

    pub fn set_active_primary(&mut self, session_id: &str, agent_id: &str) -> anyhow::Result<()> {
        let project = self.project.clone();
        if self.is_session_busy_for(session_id) {
            let binding = self.session_binding(session_id);
            if let Some(proj) = self.projection_mut(session_id) {
                proj.push_operation_error(
                    OperationKind::SetActivePrimary,
                    ErrorCode::AgentAlreadyRunning,
                    "agent already running".into(),
                    &project,
                    &binding,
                );
            }
            return Ok(());
        }
        // A child session's identity comes from its agent profile and is fixed
        // for the child's whole life: there is no "switch the agent" concept for
        // subagents (the profile name seeds the row at launch). Config stays
        // editable — model / thinking tier / context mode are session-owned and
        // work identically to a primary session.
        if self.service.is_child_session(session_id) {
            let binding = self.session_binding(session_id);
            if let Some(proj) = self.projection_mut(session_id) {
                proj.push_operation_error(
                    OperationKind::SetActivePrimary,
                    ErrorCode::InvalidRequest,
                    "child session identity is fixed by its agent profile".into(),
                    &project,
                    &binding,
                );
            }
            return Ok(());
        }
        self.runtime.apply_non_engine()?;
        match crate::runtime::RuntimeHandle::validate_primary_agent(
            &self.runtime.resolved,
            agent_id,
        ) {
            Ok(()) => {
                self.service
                    .set_agent_id(session_id, agent_id.to_string())
                    .map_err(|e| anyhow::anyhow!("{e}"))?;
                // Only agent_id — do not touch model_id (decoupled sticky).
                let binding = self.session_binding(session_id);
                if let Some(proj) = self.projection_mut(session_id) {
                    proj.context_window = binding.context_window;
                    proj.push_operation_ok(OperationKind::SetActivePrimary, &project, &binding);
                }
                Ok(())
            }
            Err(e) => {
                let binding = self.session_binding(session_id);
                if let Some(proj) = self.projection_mut(session_id) {
                    proj.push_operation_error(
                        OperationKind::SetActivePrimary,
                        ErrorCode::InvalidRequest,
                        e.to_string(),
                        &project,
                        &binding,
                    );
                }
                Ok(())
            }
        }
    }

    /// Persist sticky session `model_id` only (does not touch `agent_id`).
    pub fn set_session_model(&mut self, session_id: &str, model_id: &str) -> anyhow::Result<()> {
        let project = self.project.clone();
        if self.is_session_busy_for(session_id) {
            let binding = self.session_binding(session_id);
            if let Some(proj) = self.projection_mut(session_id) {
                proj.push_operation_error(
                    OperationKind::SetModel,
                    ErrorCode::AgentAlreadyRunning,
                    "agent already running".into(),
                    &project,
                    &binding,
                );
            }
            return Ok(());
        }
        self.runtime.apply_non_engine()?;
        let selectable = self
            .runtime
            .resolved
            .catalog()
            .model(model_id)
            .is_some_and(|model| {
                self.runtime
                    .resolved
                    .provider_api_key(&model.provider_id)
                    .is_some()
            });
        if !selectable {
            let binding = self.session_binding(session_id);
            if let Some(proj) = self.projection_mut(session_id) {
                proj.push_operation_error(
                    OperationKind::SetModel,
                    ErrorCode::InvalidRequest,
                    format!("model '{model_id}' not found"),
                    &project,
                    &binding,
                );
            }
            return Ok(());
        }
        let previous = self
            .service
            .session_model_id(session_id)
            .unwrap_or_default();
        if previous == model_id {
            // Re-selecting the current model is an idempotent success. There is
            // no state transition, so no control-plane row and no revision.
            let binding = self.session_binding(session_id);
            if let Some(proj) = self.projection_mut(session_id) {
                proj.push_operation_ok(OperationKind::SetModel, &project, &binding);
            }
            return Ok(());
        }
        // Port the current view before committing the switch: the user sees
        // what the new target will drop, and a target that cannot serve this
        // session is rejected here instead of on the next turn.
        let preview =
            match self
                .service
                .preview_session_model(&self.runtime.resolved, session_id, model_id)
            {
                Ok(preview) => preview,
                Err(error) => {
                    let binding = self.session_binding(session_id);
                    if let Some(proj) = self.projection_mut(session_id) {
                        proj.push_operation_error(
                            OperationKind::SetModel,
                            ErrorCode::InvalidRequest,
                            error.to_string(),
                            &project,
                            &binding,
                        );
                    }
                    return Ok(());
                }
            };
        if let Some(block) = preview.report.blocked {
            let binding = self.session_binding(session_id);
            if let Some(proj) = self.projection_mut(session_id) {
                proj.push_operation_error(
                    OperationKind::SetModel,
                    ErrorCode::InvalidRequest,
                    format!(
                        "model '{model_id}' cannot serve this session: {}",
                        block.message()
                    ),
                    &project,
                    &binding,
                );
            }
            return Ok(());
        }
        // State and history share one writer transaction: either the model
        // changes and the switch row exists, or neither change lands.
        let record = serde_json::json!({
            "schema": 1,
            "from": previous,
            "to": model_id,
            "at_seq": preview.at_seq,
            "report": {
                "items_in": preview.report.items_in,
                "items_out": preview.report.items_out,
                "reasoning_dropped": preview.report.reasoning_dropped,
                "ciphertext_stripped": preview.report.ciphertext_stripped,
                "signatures_stripped": preview.report.signatures_stripped,
                "projected_parts": preview.report.projected_parts,
            }
        });
        let change_seq = self
            .service
            .set_session_model_with_change(session_id, Some(model_id.to_string()), &record)
            .map_err(|e| anyhow::anyhow!("{e}"))?;
        tracing::info!(
            target: "litecode.debug.model_switch",
            session_id,
            from = %previous,
            to = %model_id,
            at_seq = preview.at_seq,
            change_seq,
            items_in = preview.report.items_in,
            items_out = preview.report.items_out,
            reasoning_dropped = preview.report.reasoning_dropped,
            ciphertext_stripped = preview.report.ciphertext_stripped,
            signatures_stripped = preview.report.signatures_stripped,
            projected_parts = preview.report.projected_parts,
            degraded = preview.report.degraded(),
            "session model switched"
        );
        let binding = self.session_binding(session_id);
        let request_model = self.resolved_model_for_binding(&binding);
        if let Some(proj) = self.projection_mut(session_id) {
            proj.context_window = binding.context_window;
            proj.set_request_model(request_model);
            proj.push_operation_ok(OperationKind::SetModel, &project, &binding);
        }
        Ok(())
    }

    pub fn set_thinking_tier(&mut self, session_id: &str, tier: &str) -> anyhow::Result<()> {
        let project = self.project.clone();
        let parsed = crate::platform_knobs::ThinkingTier::parse(tier).ok_or_else(|| {
            anyhow::anyhow!("invalid thinking_tier '{tier}' (expected low|medium|high)")
        })?;
        if self.is_session_busy_for(session_id) {
            let binding = self.session_binding(session_id);
            if let Some(proj) = self.projection_mut(session_id) {
                proj.push_operation_error(
                    OperationKind::SetThinkingTier,
                    ErrorCode::AgentAlreadyRunning,
                    "agent already running".into(),
                    &project,
                    &binding,
                );
            }
            return Ok(());
        }
        self.service
            .set_thinking_tier(session_id, parsed)
            .map_err(|e| anyhow::anyhow!("{e}"))?;
        let binding = self.session_binding(session_id);
        if let Some(proj) = self.projection_mut(session_id) {
            proj.push_operation_ok(OperationKind::SetThinkingTier, &project, &binding);
        }
        Ok(())
    }

    pub fn set_context_mode(&mut self, session_id: &str, mode: &str) -> anyhow::Result<()> {
        let project = self.project.clone();
        let parsed = crate::platform_knobs::ContextMode::parse(mode).ok_or_else(|| {
            anyhow::anyhow!("invalid context_mode '{mode}' (expected standard|max)")
        })?;
        if self.is_session_busy_for(session_id) {
            let binding = self.session_binding(session_id);
            if let Some(proj) = self.projection_mut(session_id) {
                proj.push_operation_error(
                    OperationKind::SetContextMode,
                    ErrorCode::AgentAlreadyRunning,
                    "agent already running".into(),
                    &project,
                    &binding,
                );
            }
            return Ok(());
        }
        self.service
            .set_context_mode(session_id, parsed)
            .map_err(|e| anyhow::anyhow!("{e}"))?;
        let binding = self.session_binding(session_id);
        if let Some(proj) = self.projection_mut(session_id) {
            proj.context_window = binding.context_window;
            proj.refresh_context_estimate();
            proj.push_operation_ok(OperationKind::SetContextMode, &project, &binding);
        }
        Ok(())
    }

